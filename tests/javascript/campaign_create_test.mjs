import assert from 'node:assert/strict';
import {draftDefinition, boundedVideo} from '../../app/portal/static/campaign-create.mjs';
const account = {platform:'google_ads', account_id:12, connection_id:34};
const mandate = {id:'a'.repeat(32), revision:7, state:'approved', paused:false, definition:{currency:'USD', accounts:[account]}};
const values = {name:'<script>literal</script>', landing_page:'https://example.invalid', budget:'0.000001', starts:'2026-10-05T12:00:00Z', ends:'2026-10-05T13:00:00Z', countries:'US, CA', languages:'en', headlines:'One\nTwo\nThree', descriptions:'First\nSecond', exact_keywords:'product', headline:'Shop', text:'Supplied'};
let draft = draftDefinition(mandate, account, values);
assert.equal(draft.budget_micros,1); assert.equal(draft.mandate_revision,7); assert.equal(draft.content.name,values.name);
assert.deepEqual(draft.content.audience.countries,['US','CA']);
assert.throws(() => draftDefinition({...mandate,paused:true},account,values));
assert.throws(() => draftDefinition(mandate,account,{...values,budget:'1e6'}));
assert.throws(() => draftDefinition(mandate,account,{...values,ends:values.starts}));
const media = {media_id:'b'.repeat(32),sha256:'c'.repeat(64),mime:'image/png'};
draft = draftDefinition(mandate,{...account,platform:'meta_ads'},values,media);
assert.equal(draft.content.kind,'meta_website_sales_image_v1'); assert.deepEqual(draft.content.media,{media_id:media.media_id,sha256:media.sha256});
assert.throws(() => draftDefinition(mandate,{...account,platform:'tiktok_ads'},values,media));
draft = draftDefinition(mandate,{...account,platform:'tiktok_ads'},values,{...media,mime:'video/mp4'});
assert.equal(draft.content.kind,'tiktok_website_conversion_video_v1');
assert.equal((await boundedVideo(new Response(new Uint8Array([1]),{headers:{'Content-Type':'video/mp4'}}))).size,1);
await assert.rejects(boundedVideo(new Response('x',{status:403})));
await assert.rejects(boundedVideo(new Response('x',{headers:{'Content-Type':'image/png'}})));
await assert.rejects(boundedVideo(new Response(null,{headers:{'Content-Type':'video/mp4'}})));
let cancelled = false;
const oversized = new ReadableStream({start(controller){controller.enqueue(new Uint8Array(64*1048576+1));},cancel(){cancelled=true;}});
await assert.rejects(boundedVideo(new Response(oversized,{headers:{'Content-Type':'video/mp4'}})));
assert(cancelled, 'oversized response cancelled');
