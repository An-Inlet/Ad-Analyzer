  assert($('campaign-media').naturalWidth === 4, 'actual private media endpoint bytes decoded');
  await fetch('/__fixture__/media-denied', {method:'POST'});
  $('review-reload').click();
  await until(() => $('media-status').textContent.includes('Media Unavailable') && !$('review-draft').disabled, 'failed image response blocks review');
  $('review-consent').checked = true; $('review-consent').dispatchEvent(new Event('change'));
  assert($('approve-campaign').disabled, 'cannot approve unseen image');
  await fetch('/__fixture__/media-denied', {method:'POST'});
  $('review-draft').value = '__DRAFT__'; $('review-draft').dispatchEvent(new Event('change'));
  await until(() => !$('campaign-preview').hidden && !$('review-draft').disabled, 'rendered preview');
  assert($('campaign-summary').textContent.includes('USD 0.00006'), 'exact micros displayed');
  assert($('campaign-copy').textContent.includes('Description one'), 'supplied copy rendered');
  assert($('media-status').textContent.includes('No Supplied Media Required'), 'text media status');
  assert($('publication-blockers').textContent.includes('Provider publication is disabled'), 'publication blocked');
  assert($('approve-campaign').disabled, 'explicit review acknowledgment');
  const firstReference = $('review-reference').textContent;
  $('review-consent').checked = true; $('review-consent').dispatchEvent(new Event('change'));
  $('approve-campaign').click();
  await until(() => $('approval-status').textContent.includes('Approved For Offline Planning'), 'approved offline revision');
  assert($('review-reference').textContent === firstReference, 'approval is exact same digest');
  const form = $('campaign-edit'); form.elements.namedItem('name').value = '<img src=x onerror=alert(1)> New Name';
  await until(() => !$('save-campaign').disabled, 'save enabled'); form.requestSubmit();
