  const current = await (await fetch(path + '/preview')).json();
  const csrf = document.cookie.split(';').map(x => x.trim()).find(x => x.startsWith('__Host-inlet_csrf=')).split('=')[1];
  const changed = await fetch(path, {method:'PUT', headers:{'Content-Type':'application/json', 'X-CSRF-Token':csrf}, body:JSON.stringify({expected_revision:2, definition:current.artifact.definition})});
